// Generates src/api/schema.d.ts from api/openapi.yaml.
// `format: binary` is mapped to Blob so that upload bodies accept File objects.
import { writeFile } from 'node:fs/promises'

import openapiTS, { astToString } from 'openapi-typescript'
import ts from 'typescript'

const specURL = new URL('../../api/openapi.yaml', import.meta.url)
const outURL = new URL('../src/api/schema.d.ts', import.meta.url)

const blob = ts.factory.createTypeReferenceNode(ts.factory.createIdentifier('Blob'))

const ast = await openapiTS(specURL, {
  transform(schemaObject) {
    if (schemaObject.format === 'binary') {
      return blob
    }
  },
})

await writeFile(
  outURL,
  `// Code generated by scripts/gen-api.mjs from api/openapi.yaml. DO NOT EDIT.\n\n${astToString(ast)}`,
)
